import assert from 'node:assert/strict';
import { createEnv, migration } from './_pglite-env';
const ADMIN='eeeeeeee-0000-0000-0000-000000000001';
const USER='eeeeeeee-0000-0000-0000-000000000002';
const OTHER='eeeeeeee-0000-0000-0000-000000000003';
async function main() {
  const env=await createEnv();
  const {q,one,userQ,userOne,anonQ,denied}=env;
  await env.addUser(ADMIN,{admin:true});
  await env.addUser(USER); await env.addUser(OTHER);
  await env.applyUpTo('20261004030000_admin_backend');
  const sql=migration('20261013010000_user_app_open_activity');
  await env.db.exec(sql);
  await q("UPDATE auth.users SET last_sign_in_at='2020-01-01T00:00:00Z' WHERE id=$1",[USER]);
  let detail=(await userOne(ADMIN,'SELECT admin_user_detail($1) AS r',[USER])).r;
  assert.equal(detail.last_app_open_at,null,'Unknown history must not use last sign-in as an app opening');
  assert.equal(await denied(()=>anonQ('SELECT record_app_open()')),true);
  await userQ(USER,'SELECT record_app_open()');
  const stamp=await one('SELECT last_opened_at, ctid::text AS row_version FROM user_app_activity WHERE user_id=$1',[USER]);
  assert.equal(new Date(stamp.last_opened_at).getUTCSeconds(),0,'Only minute precision is stored');
  assert.ok(Date.now()-new Date(stamp.last_opened_at).getTime()<120000);
  await userQ(USER,'SELECT record_app_open()');
  assert.equal((await one('SELECT ctid::text AS row_version FROM user_app_activity WHERE user_id=$1',[USER])).row_version,stamp.row_version,'No repeated writes within one minute');
  assert.equal((await userQ(USER,'SELECT * FROM user_app_activity')).rows.length,0,'Even own activity timestamps are not publicly readable');
  assert.equal(await denied(()=>anonQ('SELECT * FROM user_app_activity')),true);
  assert.equal(await denied(()=>userQ(USER,"UPDATE user_app_activity SET last_opened_at='2099-01-01' WHERE user_id=$1",[OTHER])),true);
  assert.equal(await denied(()=>userQ(USER,'INSERT INTO user_app_activity VALUES ($1,now())',[OTHER])),true);
  assert.equal(await denied(()=>userQ(USER,'SELECT record_app_open($1)',[OTHER])),true,'No parameter allows forging another user');
  assert.equal(await denied(()=>userQ(USER,'SELECT admin_user_detail($1)',[OTHER])),true);
  await q("INSERT INTO user_app_activity VALUES ($1,now()-interval '2 days')",[OTHER]);
  await q("UPDATE auth.users SET last_sign_in_at='2099-01-01' WHERE id=$1",[OTHER]);
  const list=(await userOne(ADMIN,"SELECT admin_list_users(NULL,'all','last_app_open',100,0) AS r")).r;
  assert.equal(list.rows[0].id,USER,'Sort uses app openings rather than auth timestamps');
  detail=(await userOne(ADMIN,'SELECT admin_user_detail($1) AS r',[USER])).r;
  assert.equal(new Date(detail.last_app_open_at).getTime(),new Date(stamp.last_opened_at).getTime());
  assert.equal(new Date(detail.auth.last_sign_in_at).getUTCFullYear(),2020,'Authentication data remains untouched');
  assert.equal((await userQ(ADMIN,'SELECT * FROM user_app_activity')).rows.length,2);
  await env.db.exec(sql);
  assert.equal((await one('SELECT count(*)::int AS n FROM user_app_activity')).n,2,'Migration is idempotent and preserves tracked activity');
  console.log('PASS: distinct opening timestamp, minute deduplication, admin-only reads, no forged user/time, sorting and migration idempotence');
  await env.db.close();
}
main().catch(e=>{console.error(e);process.exitCode=1;});
