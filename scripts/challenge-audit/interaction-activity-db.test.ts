import assert from 'node:assert/strict';
import { createEnv, migration } from './_pglite-env';
const ADMIN='eeeeeeee-0000-0000-0000-000000000001';
const USER='eeeeeeee-0000-0000-0000-000000000002';
const OTHER='eeeeeeee-0000-0000-0000-000000000003';
async function main() {
  const env=await createEnv();
  const {q,one,userQ,userOne,denied}=env;
  await env.addUser(ADMIN,{admin:true}); await env.addUser(USER); await env.addUser(OTHER);
  await env.applyUpTo('20261010032000_people_discovery');
  await q("INSERT INTO code_snippets(user_id,title,code,language,created_at) VALUES($1,'Historical','print(1)','python','2020-01-01')",[USER]);
  await q("UPDATE auth.users SET last_sign_in_at='2099-01-01' WHERE id=$1",[USER]);
  await q("INSERT INTO user_activity_days(user_id,day,lessons,frozen,first_at) VALUES($1,'2024-01-01',0,true,'2024-01-01')",[USER]);
  await env.db.exec(migration('20261013010000_user_app_open_activity'));
  const sql=migration('20261013011000_user_interaction_activity');
  await env.db.exec(sql);
  let a=await one('SELECT * FROM user_app_activity WHERE user_id=$1',[USER]);
  assert.equal(a.last_opened_at,null,'Historical interactions never pretend to be an app opening');
  assert.equal(new Date(a.last_interacted_at).getUTCFullYear(),2020,'Historical action ignores sign-ins and frozen streak days');
  const snippet=(await userOne(USER,"INSERT INTO code_snippets(user_id,title,code,language,is_public) VALUES($1,'My code','print(2)','python',true) RETURNING id",[USER])).id;
  a=await one('SELECT * FROM user_app_activity WHERE user_id=$1',[USER]);
  assert.ok(Date.now()-new Date(a.last_interacted_at).getTime()<120000,'Old publish contract updates interaction time');
  assert.equal(a.last_opened_at,null);
  await q("UPDATE user_app_activity SET last_interacted_at=now()-interval '5 days' WHERE user_id=$1",[USER]);
  const old=(await one('SELECT last_interacted_at FROM user_app_activity WHERE user_id=$1',[USER])).last_interacted_at;
  await userQ(OTHER,'INSERT INTO code_likes(user_id,snippet_id) VALUES($1,$2)',[OTHER,snippet]);
  assert.equal(new Date((await one('SELECT last_interacted_at FROM user_app_activity WHERE user_id=$1',[USER])).last_interacted_at).getTime(),new Date(old).getTime(),'Other people liking a post do not make its author active');
  assert.ok((await one('SELECT last_interacted_at FROM user_app_activity WHERE user_id=$1',[OTHER])).last_interacted_at);
  await userQ(ADMIN,"UPDATE profiles SET full_name='Admin edit' WHERE id=$1",[USER]);
  assert.equal(new Date((await one('SELECT last_interacted_at FROM user_app_activity WHERE user_id=$1',[USER])).last_interacted_at).getTime(),new Date(old).getTime(),'Admin edits are not attributed to the target user');
  const notification=(await one("INSERT INTO notifications(id,user_id,type,title,message) VALUES(gen_random_uuid(),$1,'system','Test','Test') RETURNING id",[USER])).id;
  assert.equal(new Date((await one('SELECT last_interacted_at FROM user_app_activity WHERE user_id=$1',[USER])).last_interacted_at).getTime(),new Date(old).getTime(),'Receiving a notification is not interacting');
  await userQ(USER,'UPDATE notifications SET read=true WHERE id=$1',[notification]);
  assert.ok(Date.now()-new Date((await one('SELECT last_interacted_at FROM user_app_activity WHERE user_id=$1',[USER])).last_interacted_at).getTime()<120000,'Reading notifications counts as an interaction');
  await env.svcQ("INSERT INTO challenge_submissions(user_id,challenge_id,passed_tests,total_tests,all_passed,code_sha256) VALUES($1,'ch-3',0,5,false,$2)",[OTHER,'a'.repeat(64)]);
  assert.ok((await one('SELECT last_interacted_at FROM user_app_activity WHERE user_id=$1',[OTHER])).last_interacted_at,'Server-verified challenge attempts are observed');
  await userQ(USER,'SELECT record_app_open()');
  a=await one('SELECT * FROM user_app_activity WHERE user_id=$1',[USER]);
  assert.ok(a.last_opened_at,'The next build records opening even when a legacy interaction row already exists');
  assert.equal((await userQ(USER,'SELECT * FROM user_app_activity')).rows.length,0);
  assert.equal(await denied(()=>userQ(USER,'SELECT _record_user_interaction()')),true);
  let detail=(await userOne(ADMIN,'SELECT admin_user_detail($1) AS r',[USER])).r;
  assert.ok(detail.last_app_open_at && detail.last_interaction_at);
  const before=new Date(detail.last_interaction_at).getTime();
  await env.db.exec(sql);
  detail=(await userOne(ADMIN,'SELECT admin_user_detail($1) AS r',[USER])).r;
  assert.ok(new Date(detail.last_interaction_at).getTime()>=before,'Repeated migration preserves activity');
  console.log('PASS: historical recovery, legacy actions, no recipient/counter/admin false positives, read interactions, service verification, separate openings, privacy and idempotence');
  await env.db.close();
}
main().catch(e=>{console.error(e.message);process.exitCode=1;});
