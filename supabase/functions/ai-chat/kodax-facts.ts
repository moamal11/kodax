/** يدمج إعدادات القاعدة مع القيم الأولية (أي مفتاح ناقص يبقى بقيمته الأولية) */
export function mergeLiveConfig(raw: Partial<Record<keyof LiveConfig, unknown>> | null | undefined): LiveConfig {
  const d = DEFAULT_LIVE_CONFIG;
  const pick = <T extends object>(base: T, v: unknown): T =>
    v && typeof v === 'object' && !Array.isArray(v) ? { ...base, ...(v as Partial<T>) } : base;
  return {
    ads: pick(d.ads, raw?.ads),
    daily_ladder: pick(d.daily_ladder, raw?.daily_ladder),
    challenge_rewards: pick(d.challenge_rewards, raw?.challenge_rewards),
    course_completion_rewards: pick(d.course_completion_rewards, raw?.course_completion_rewards),
    field_bundle: pick(d.field_bundle, raw?.field_bundle),
    ai_quota: pick(d.ai_quota, raw?.ai_quota),
    progression: pick(d.progression, raw?.progression),
    streak: pick(d.streak, raw?.streak),
    goals: pick(d.goals, raw?.goals),
    solutions: pick(d.solutions, raw?.solutions),
    prices: (raw?.prices as Record<string, number>) ?? {},
  };
}

const pct = (x: number) => `${Math.round(x * 100)}%`;
const maxAi = (c: LiveConfig) => c.ai_quota.daily_limit + c.ai_quota.ad_bonus * c.ai_quota.max_ad_bonuses_per_day;

