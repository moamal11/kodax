-- ============================================================================
-- الإشعارات: ساعات الهدوء مطفأة افتراضياً
-- ----------------------------------------------------------------------------
-- كانت مفعّلة افتراضياً (23:00–08:00 بتوقيت بغداد) لكل مستخدم، فتؤجّل الإعجابات والتعليقات
-- والمتابعات وحملات Kodax تسع ساعات إلى الصباح بلا أي إشارة للمستخدم — فبدا أن الإشعارات
-- لا تعمل. الآن كل الأنواع تُرسَل فوراً، ومن يريد الهدوء ليلاً يفعّله من Profile → الإشعارات
-- (المفتاح الموجود يضبط 23:00–08:00 كما كان).
--
-- quiet_start = quiet_end = 0 هو "متوقف" بحسب المنطق القائم في _push_enqueue وشاشة الإعدادات.
-- منطق التأجيل نفسه يبقى كما هو لمن يفعّلها (انظر 20261004060000 و20261004070000).
-- ============================================================================

ALTER TABLE notification_preferences
  ALTER COLUMN quiet_start SET DEFAULT 0,
  ALTER COLUMN quiet_end SET DEFAULT 0;

-- الصفوف التي ما زالت على الافتراضي القديم (23→08) تُطفأ؛
-- ومن اختار نافذة مختلفة بنفسه يبقى اختياره كما هو
UPDATE notification_preferences
SET quiet_start = 0, quiet_end = 0, updated_at = NOW()
WHERE quiet_start = 23 AND quiet_end = 8;
